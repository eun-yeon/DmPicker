//! # dmpicker-search
//!
//! DJMAX RESPECT V 곡 이동 팝업용 로컬 곡 검색, 할당을 거의 안 함
//! **한글 IME 조합 중 갱신까지 포함해 키를 칠 때마다** 부르는 걸 전제로 함
//!
//! ```no_run
//! use dmpicker_search::{Catalog, Searcher};
//! let cat = Catalog::load("data/djmaxgg_songs.json").unwrap();
//! let searcher = Searcher::new(&cat);
//! for hit in searcher.search("빗", 10) {          // "비상"을 치는 중의 IME 상태
//!     println!("{} ({})", cat.songs[hit.index].name, hit.score);
//! }
//! ```
//!
//! ## 매칭
//! * **Compact** 비교: 소문자, 전각은 ASCII로, 악센트 제거, 공백·문장 부호·기호 무시
//! * **타자 자모**: 한글은 2벌식 타자 순서로도 비교 (겹모음·겹받침은 나누고 ㄲㄸㅃㅆㅉ는 키 하나)
//!   그래서 IME 조합 중간 상태 ("ㅂ", "비", "빗", "비사", "비상")도 다 맞음
//! * **초성**: 자음만 있는 검색어 ("ㅂㅅ", "ㄱㅂㄲ", IME의 "ㅄ")는 이름·별칭의 초성과 비교
//! * **필드 순위**: 이름 > 제목 별칭 (djmax.gg `segments`, 한국어 발음 포함) > 작곡가
//!   (+ `composerKeys`) > DLC·장르·팩 이름
//! * **IME 모드 착오**: "뇆샤ㅡㄷ"로 Showtime, "ㄹㄷㅁㄱ"로 FEAR, "qltkd"로 비상이 나옴 (낮은 등급)
//! * **오타**: 검색어와 오타 하나 (4글자 이상, 타자 자모 5개 이상) 또는 둘 (8+ / 10+) 차이로
//!   시작하는 이름·별칭, 첫 글자는 친 그대로 ("fermoin"으로 Fermion, "설렘"으로 설레임)
//! * **퍼지**: 더 나은 결과로 `limit`가 안 차면 순서만 맞는 부분열로 채움
//!
//! ## 점수 등급 (높을수록 좋음)
//! | 등급 | 점수 |
//! |---|---|
//! | compact 내 키워드 완전 일치 (나머지는 제목 별칭과 같음) | 1001 |
//! | compact 이름 완전 일치 | 1000 |
//! | 제목 별칭 완전 일치 | 950 |
//! | 이름이 검색어를 온전한 단어로 시작 ("zero"로 Zero-Break) | 920 |
//! | 이름 앞부분 (첫 단어 안, "zero"로 Zeroize) | 900 |
//! | 별칭 앞부분 | 850 |
//! | 이름 안 단어 시작 (온전한 단어면 +10) | 800 − 위치 |
//! | 약어 완전 일치 / 앞부분 ("ngs") | 790 / 765 |
//! | 작곡가 완전 일치 (아티스트 이름·별칭 전체) | 760 |
//! | 이름 부분 일치 (단어 중간) | 750 − 위치 |
//! | 작곡가 앞부분 / 단어 시작 ("escape"로 Forte Escape) | 710 / 700 − 위치 |
//! | 별칭 부분 일치 | 700 − 위치 |
//! | *위 항목이 타자 자모 단계에서만 맞음* | −30 |
//! | 초성 이름 완전 일치 / 앞부분 / 단어 / 부분 | 700 / 680 / 650 / 630 |
//! | 초성 별칭 완전 일치 / 앞부분 / 부분 | 670 / 650 / 600 |
//! | DLC·장르·팩 완전 일치 / 앞부분 / 단어 시작 | 540 / 500 / 480 − 위치 |
//! | 작곡가 부분 일치 / DLC 부분 일치 | 460 / 420 (− 위치) |
//! | IME 모드 착오 (이름·별칭 앞부분만) | 등급 − 300 |
//! | 오타 1–2개 차이로 시작하는 이름·별칭 | 390 − 오타당 30 (별칭은 − 10) |
//! | 순서만 맞는 부분열 퍼지 (남은 자리 채움) | 100..=310 |
//!
//! 위치는 키 안에서 매치가 시작하는 자리, 최대 20
//! 단어 중간에서 시작한 매치는 다음 단어로 넘어가면 안 됨 ("t-he lo-st"의 "helo"는 안 맞음)
//! 동점이면 (compact) 이름이 짧은 것 먼저, 다음은 이름순
//! 초성 등급은 자음만 있는 검색어에만 쓰여서 작곡가 등급과 겹칠 일 없음
//!
//! ## 조건 검색
//! 검색어 전체가 레벨 조건 ("sc15", "4b mx14-15", "ㄴㅊ14~15"), BPM 조건 ("bpm150", "bpm:150~180", "bpm200~")
//! 또는 둘 다면 ("sc14 bpm150~180") [`Filter`]로 맞는 곡을 제목순으로 모음
//! 난이도가 없거나 ("15", "4b15") 꼴이 안 맞으면 위의 텍스트 검색

